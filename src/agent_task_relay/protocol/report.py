"""Result report generation for the bridge outbox."""
from __future__ import annotations

import datetime as dt
from agent_task_relay.protocol.models import RunnerResult, StateRecord
from agent_task_relay.transport.redactor import redact_secrets, sanitize_markdown_fences


def generate_result_report(
    task_id: str,
    state_record: StateRecord,
    runner_result: RunnerResult,
) -> str:
    """Generate a clean, structured Markdown result report for the bridge outbox."""
    status_upper = state_record.status.upper()
    runner = state_record.runner
    duration = f"{state_record.duration_seconds:.1f}s" if state_record.duration_seconds is not None else "N/A"
    finished = state_record.finished_at or dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")

    sanitized_response = sanitize_markdown_fences(redact_secrets(runner_result.summary or runner_result.stdout))

    lines = [
        f"# {task_id} · {status_upper}",
        "",
        "| Attribute | Value |",
        "| --- | --- |",
        f"| **Status** | `{state_record.status}` |",
        f"| **Runner** | `{runner}` |",
        f"| **Task SHA-256** | `{state_record.sha256}` |",
        f"| **Host** | `{state_record.host}` |",
        f"| **Duration** | `{duration}` |",
        f"| **Finished At** | `{finished}` |",
        f"| **Attempt** | `{state_record.attempt}` |",
        "",
    ]

    if runner_result.error_blockers:
        lines.extend([
            "## ⚠️ Blockers & Review Required",
            "",
        ])
        for blocker in runner_result.error_blockers:
            lines.append(f"- {blocker}")
        lines.append("")

    if runner_result.changed_files:
        lines.extend([
            "## 📝 Changed Files",
            "",
        ])
        for f in runner_result.changed_files:
            lines.append(f"- `{f}`")
        lines.append("")

    if runner_result.test_results:
        lines.extend([
            "## 🧪 Test Results",
            "",
            f"```json",
            f"{runner_result.test_results}",
            f"```",
            "",
        ])

    lines.extend([
        "## 📋 Agent Response Summary",
        "",
        "> **Notice:** This report was generated by an automated coding agent. "
        "Inspect all source diffs and run independent tests before accepting changes.",
        "",
        sanitized_response if sanitized_response.strip() else "*(No textual response was returned by runner)*",
        "",
    ])

    return "\n".join(lines)


def generate_rejection_report(
    task_id: str,
    sha256: str,
    reason: str,
    host: str,
) -> str:
    """Generate a result report for an explicitly rejected task."""
    now_iso = dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")
    return "\n".join([
        f"# {task_id} · REJECTED",
        "",
        "| Attribute | Value |",
        "| --- | --- |",
        f"| **Status** | `rejected` |",
        f"| **Task SHA-256** | `{sha256}` |",
        f"| **Host** | `{host}` |",
        f"| **Rejected At** | `{now_iso}` |",
        "",
        "## 🚫 Task Rejection Reason",
        "",
        f"{reason.strip() or 'Task was rejected by operator during manual review.'}",
        "",
        "> The task will not be executed by the local coding agent. "
        "Review or submit a revised task packet with a new task ID if needed.",
        "",
    ])
